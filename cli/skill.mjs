import { readFile, writeFile, mkdir, realpath } from 'node:fs/promises'
import { execFileSync } from 'node:child_process'
import { homedir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { skillText } from '../prompt.js'

const binary = fileURLToPath(new URL('../bin/dsh-diagram.mjs', import.meta.url))
export async function cliCommand(override) {
  if (override) return override
  try {
    const candidates = execFileSync(process.platform === 'win32' ? 'where' : 'which', ['dsh-diagram'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim().split(/\r?\n/)
    const own = await realpath(binary)
    for (const candidate of candidates) {
      if (await realpath(candidate) === own) return 'dsh-diagram'
      // npm's Windows launcher is a wrapper, not a symlink.
      if (process.platform === 'win32') {
        const target = path.join(path.dirname(candidate), 'node_modules/dsh-diagram/bin/dsh-diagram.mjs')
        if (await realpath(target).catch(() => null) === own) return 'dsh-diagram'
      }
    }
  } catch {}
  const quoted = process.platform === 'win32' ? JSON.stringify(binary) : '"' + binary.replace(/["\\$`]/g, '\\$&') + '"'
  return `node ${quoted}`
}
export async function printSkill({ cli } = {}) {
  return skillText({ cli: await cliCommand(cli) })
}
export async function installSkill({ to = path.join(homedir(), '.agents/skills'), cli, force = false } = {}) {
  const target = path.resolve(to, 'dsh-diagram/SKILL.md')
  let existing
  try { existing = await readFile(target, 'utf8') } catch (e) { if (e.code !== 'ENOENT') throw e }
  if (existing !== undefined && !existing.includes('<!-- generated by dsh-diagram -->') && !force) {
    throw new Error(`Refusing to overwrite an unrelated skill at ${target}; use --force to replace it`)
  }
  const text = await printSkill({ cli })
  await mkdir(path.dirname(target), { recursive: true })
  await writeFile(target, text)
  return target
}
