for (const [name, options] of [['DSH', undefined], ['standalone', standalone]]) {
  test(`the ${name} format guide contains a valid diagram example`, async () => {
    const text = formatGuide(options)
    const start = text.indexOf('// diagram v1\nmodel')
    assert.ok(start >= 0, 'the neutral example has a format header')
    const result = await compute(text.slice(start))
    assert.deepEqual(result.errors, [])
    assert.deepEqual(result.problems, [])
  })

  test(`the ${name} format guide quotes the engine readability limits`, () => {
    const text = formatGuide(options)
    assert.ok(text.includes(`At most ${RULES.children} children per group and ${RULES.depth} levels`))
    assert.ok(text.includes(`schema > up to ${RULES.depth - 2} nested groups > leaf`))
    assert.ok(text.includes(`title ≤ ${RULES.title} chars, description ≤ ${RULES.description}, technology ≤ ${RULES.technology}, relation label ≤ ${RULES.relation}`))
    assert.equal(RULES.elements, undefined, 'there is no global element cap')
  })
}

test('parse and refusal reports retain host wording, locations and truncation', () => {
  const errors = [
    { line: 2, character: 4, message: 'Unexpected token' },
    { line: 8, character: 0, message: 'Expected closing brace' },
  ]
  assert.equal(errorReport({ rel: '.diagram/S.c4', errors, maxErrors: 1 }), [
    "[diagram] .diagram/S.c4 does not parse — the user's map tab shows the last valid version plus these errors. Fix them now:",
    '  .diagram/S.c4:3:4  Unexpected token',
    '  (+1 more)',
    'Reminder: first line `// diagram v1`; tags go first inside braces; ids use letters/digits/_; no `specification` block needed.',
  ].join('\n'))
  assert.equal(refusalReport({ rel: '.diagram/S.c4', problems: errors, rules: RULES, maxErrors: 1 }), [
    '[diagram] .diagram/S.c4 refused: too heavy for the user to read at a glance (not kept as a version). Fix it now:',
    '  .diagram/S.c4:3  Unexpected token',
    '  (+1 more)',
    `Rules: architecture only (no task/proof boxes), every element inside a schema group except person/external, ≤${RULES.children} children per group, ≤${RULES.depth} levels, ≤${RULES.viewNodes} boxes per view, titles ≤${RULES.title} chars, detail in metadata.`,
  ].join('\n'))
})

test('valid reports accept explicit host or CLI presentation without carrying state', () => {
  const result = {
    views: [{ id: 'shop_view', nodes: [{}, {}] }],
    viewOfElement: { shop: 'shop_view', 'shop.api': 'api_view' },
    schemas: [{ element: 'shop', view: 'shop_view', title: 'Web shop' }],
    extras: [{ title: 'Checkout' }],
  }
  const icons = 'Icons: a neutral icon hint.'
  const link = 'Link to put in your message (a click opens the interactive tab): [Diagram](</w/.diagram/S.c4>)'
  assert.equal(okReport({ result, version: 2, icons, link }), [
    '[diagram] Diagram v2 valid and shown to the user: Web shop (2 boxes), 1 drill-down view(s), flows: Checkout.',
    icons,
    link,
  ].join('\n'))
  const cliOptions = { result, icons, shown: '', link: null }
  const cliText = '[diagram] Diagram valid: Web shop (2 boxes), 1 drill-down view(s), flows: Checkout.\n' + icons
  assert.equal(okReport(cliOptions), cliText)
  assert.equal(okReport(cliOptions), cliText, 'icon line repetition is up to the caller')
  assert.equal(okReport({ result: { views: [], schemas: [], extras: [] }, shown: '', link: null }), '[diagram] Diagram valid: no schema.')
})

async function workspace(t) {
  const dir = await mkdtemp(path.join(tmpdir(), 'dsh-diagram-shared-'))
  t.after(async () => {
    // Verify the resolved cleanup target is precisely this test's temporary workspace.
    assert.equal(path.dirname(path.resolve(dir)), path.resolve(tmpdir()))
    assert.match(path.basename(dir), /^dsh-diagram-shared-/)
    await rm(dir, { recursive: true, force: true })
  })
  return dir
}

test('shared history uses explicit directories, unchanged names and source deduplication', async (t) => {
  const dir = path.join(await workspace(t), 'history')
  const source = '// diagram v1\nmodel {}\n'
  assert.deepEqual(await lastSnapshot(dir), { count: 0 })
  assert.equal(await differsFromLastSnapshot(dir, source), true)
  assert.equal(await snapshot(dir, source), 1)
  const first = await lastSnapshot(dir)
  assert.equal(first.count, 1)
  assert.equal(first.index, 1)
  assert.match(first.last, /^0001-\d{8}T\d{6}Z\.c4$/)
  assert.equal(await readFile(path.join(dir, first.last), 'utf8'), source)
  assert.equal(await differsFromLastSnapshot(dir, source), false)
  assert.equal(await snapshot(dir, source), 1)
  assert.equal((await readdir(dir)).length, 1)
  const changed = source + '// Updated\n'
  assert.equal(await differsFromLastSnapshot(dir, changed), true)
  assert.equal(await snapshot(dir, changed), 2)
  const second = await lastSnapshot(dir)
  assert.equal(second.count, 2)
  assert.equal(second.index, 2)
  assert.match(second.last, /^0002-\d{8}T\d{6}Z\.c4$/)
  assert.equal(await readFile(path.join(dir, second.last), 'utf8'), changed)
})

test('shared ignore creation preserves existing files and the original host contents', async (t) => {
  const dir = await workspace(t)
  const created = path.join(dir, '.diagram')
  await ensureIgnored(created)
  assert.equal(await readFile(path.join(created, '.gitignore'), 'utf8'), GITIGNORE)
  assert.equal(GITIGNORE, '# Created by dsh-diagram: conversation diagrams stay out of git.\n*\n')
  await ensureIgnored(created)
  assert.equal(await readFile(path.join(created, '.gitignore'), 'utf8'), GITIGNORE)
  const existing = path.join(dir, 'existing')
  await mkdir(existing)
  await writeFile(path.join(existing, '.gitignore'), '# Keep these rules\n*.c4\n')
  await ensureIgnored(existing)
  assert.equal(await readFile(path.join(existing, '.gitignore'), 'utf8'), '# Keep these rules\n*.c4\n')
})
