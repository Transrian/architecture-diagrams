test('the skill has Agent Skills frontmatter, a generated marker and portable commands', () => {
  const text = skillText({ cli: 'dsh-diagram' })
  assert.ok(text.startsWith('---\nname: dsh-diagram\n'))
  const frontmatter = /^---\nname: ([a-z0-9]+(?:-[a-z0-9]+)*)\ndescription: ([^\n]+)\n---\n/.exec(text)
  assert.ok(frontmatter, 'valid lowercase skill name and one-line description')
  assert.equal(frontmatter[1], 'dsh-diagram')
  assert.ok(frontmatter[2].length > 0 && frontmatter[2].length <= 1024)
  assert.ok(text.slice(frontmatter[0].length).startsWith('<!-- generated by dsh-diagram -->\n'))
  assert.ok(text.includes('`dsh-diagram render <file>`'))
  assert.ok(text.includes('`dsh-diagram serve <file>`'))
  assert.ok(text.includes('list `.diagram/*.c4`'))
  assert.ok(text.includes('`file://` link'))
  assert.ok(text.endsWith(formatGuide(standalone)), 'the skill uses the shared format guide')
  assert.doesNotMatch(text, /\b(?:DSH|plugin|tab|conversation|subagent)\b/)
})

